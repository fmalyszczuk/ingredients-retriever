-- User accounts. Passwords are never stored: only a salted, slow hash (BCrypt, with its algorithm prefix so the
-- scheme can be upgraded later without a migration of existing users).
CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254)                NOT NULL,
    password_hash VARCHAR(255)                NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    enabled       BOOLEAN                     NOT NULL DEFAULT TRUE
);

-- One account per email address, ignoring case, enforced by the database whatever the application does.
CREATE UNIQUE INDEX uq_users_email ON users (lower(email));
