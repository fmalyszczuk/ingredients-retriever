-- Hibernate only validates against this schema (spring.jpa.hibernate.ddl-auto=validate); it never changes it.

CREATE TABLE recipes
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255)                                         NOT NULL,
    source_type      VARCHAR(255)                                         NOT NULL,
    -- The URL, the dish name that was typed, or the uploaded file name. URLs can be long.
    source_reference VARCHAR(2048),
    created_at       TIMESTAMP(6) WITH TIME ZONE                          NOT NULL,
    CONSTRAINT ck_recipes_source_type CHECK (source_type IN ('URL', 'TEXT', 'FILE', 'MANUAL'))
);

CREATE TABLE ingredients
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255)  NOT NULL,
    quantity  NUMERIC(12, 3),
    unit      VARCHAR(255),
    recipe_id BIGINT        NOT NULL,
    CONSTRAINT fk_ingredients_recipe FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE CASCADE
);

CREATE INDEX ix_ingredients_recipe_id ON ingredients (recipe_id);

CREATE TABLE shopping_list_items
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255)  NOT NULL,
    quantity  NUMERIC(12, 3),
    unit      VARCHAR(255),
    purchased BOOLEAN       NOT NULL DEFAULT FALSE
);

-- One row per item name, ignoring case ("Eggs" and "eggs" are the same item). The application looks items up the
-- same way (lower(name)), so concurrent requests can never create duplicates, whatever the code does.
CREATE UNIQUE INDEX uq_shopping_list_items_name ON shopping_list_items (lower(name));
