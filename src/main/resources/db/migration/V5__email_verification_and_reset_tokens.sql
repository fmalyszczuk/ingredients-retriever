-- Email verification and password reset.
--
-- Accounts that exist already were created before addresses were verified; they are marked verified so that nobody is
-- locked out by this migration. New accounts start unverified.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE users SET email_verified = TRUE;

-- One-time links sent by email. Only a SHA-256 hash of the token is stored, so a copy of the database cannot be used
-- to verify addresses or reset passwords. A token is spent by setting used_at, and is also dead once expires_at passes.
CREATE TABLE account_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                      NOT NULL,
    type       VARCHAR(32)                 NOT NULL,
    token_hash VARCHAR(64)                 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_account_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_account_tokens_type CHECK (type IN ('VERIFY_EMAIL', 'RESET_PASSWORD')),
    CONSTRAINT uq_account_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX ix_account_tokens_user_id ON account_tokens (user_id);
CREATE INDEX ix_account_tokens_expires_at ON account_tokens (expires_at);
